-- Optional Supabase schema for moving data from browser storage to a shared database.
create table if not exists public.debtors (
  id bigint generated by default as identity primary key,
  name text not null,
  type text not null default 'individual' check (type in ('individual', 'company')),
  company_number text,
  cr_number text,
  phone text,
  total numeric(14,2) not null default 0,
  paid numeric(14,2) not null default 0,
  due date,
  notes text,
  rep_id bigint,
  promise_date date,
  promise_amount numeric(14,2),
  created_at timestamptz not null default now()
);

create table if not exists public.debtors_activity (
  id bigint generated by default as identity primary key,
  debtor_id bigint not null references public.debtors(id) on delete cascade,
  type text not null check (type in ('payment', 'follow')),
  activity_date date not null default current_date,
  amount numeric(14,2),
  method text,
  note text,
  created_at timestamptz not null default now()
);

create table if not exists public.reps (
  id bigint primary key,
  name text not null,
  phone text,
  area text,
  created_at timestamptz not null default now()
);

create table if not exists public.app_settings (
  id bigint primary key,
  settings jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);


create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  date timestamptz not null default now(),
  "user" text not null,
  action text not null,
  details text,
  created_at timestamptz not null default now()
);

alter table public.debtors enable row level security;
alter table public.debtors_activity enable row level security;
alter table public.reps enable row level security;
alter table public.app_settings enable row level security;
alter table public.audit_log enable row level security;





